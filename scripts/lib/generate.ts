// The generation steps of `pnpm gen`, callable in-process (verify, gate).

import { pathToFileURL } from 'node:url';
import type { ApiJson } from '../../src/lib/docs/api-types.ts';
import { analyzeLibrary, hasModuleIndex, toApiComponent } from './analysis.ts';
import type { Library } from './analysis.ts';
import { buildLayers } from './css.ts';
import type { LayerBuild } from './css.ts';
import { PATHS, exists, rel, stableJson, writeAtomic } from './util.ts';

export const GENERATED = 'GENERATED by scripts/gen.ts — do not edit.';

export interface StepResult {
	step: string;
	ok: boolean;
	summary: string;
}

export async function stepSprings(): Promise<StepResult> {
	if (!exists(PATHS.genSprings)) return { step: 'springs', ok: true, summary: 'skipped (scripts/gen-springs.ts not present yet)' };
	try {
		const mod = (await import(pathToFileURL(PATHS.genSprings).href)) as { run?: () => Promise<void> | void };
		if (typeof mod.run !== 'function') return { step: 'springs', ok: false, summary: 'scripts/gen-springs.ts does not export run()' };
		await mod.run();
		return { step: 'springs', ok: true, summary: 'spring tokens regenerated' };
	} catch (err) {
		return { step: 'springs', ok: false, summary: `scripts/gen-springs.ts failed: ${(err as Error).message}` };
	}
}

export function stepStyles(layers: LayerBuild = buildLayers()): StepResult {
	const a = writeAtomic(PATHS.customCss, layers.css);
	const b = writeAtomic(PATHS.classesJson, stableJson(layers.classes));
	writeAtomic(PATHS.cssMapJson, stableJson(layers.segments));
	const kitCount = layers.files.filter((f) => f.name.startsWith('components/')).length;
	return {
		step: 'styles',
		ok: true,
		summary: `${layers.files.length - kitCount} layers + ${kitCount} kit fragments → ${rel(PATHS.customCss)} (${layers.codeLines} lines, ${layers.classes.length} classes)${a || b ? '' : ' · unchanged'}`
	};
}

export function barrelSource(lib: Library): string {
	const lines = [`// ${GENERATED} Run \`pnpm gen\`.`, ''];
	let n = 0;
	for (const c of lib.components) {
		if (!c.hasIndex) continue;
		lines.push(`export * from './components/${c.ref.kit}/${c.ref.slug}/index.js';`);
		n++;
	}
	if (n) lines.push('');
	if (hasModuleIndex(PATHS.motion)) lines.push(`export * from './motion/index.js';`);
	if (hasModuleIndex(PATHS.theme)) lines.push(`export * from './theme/index.js';`);
	lines.push(`export * from './internal/tokens.js';`);
	lines.push(`export type { ComponentDoc } from './docs/define.js';`);
	return lines.join('\n') + '\n';
}

export function stepBarrel(lib: Library): StepResult {
	const changed = writeAtomic(PATHS.barrel, barrelSource(lib));
	const n = lib.components.filter((c) => c.hasIndex).length;
	return { step: 'barrel', ok: true, summary: `${rel(PATHS.barrel)} — ${n} component${n === 1 ? '' : 's'}${changed ? '' : ' · unchanged'}` };
}

export function apiJson(lib: Library): ApiJson {
	return { generated: GENERATED, components: lib.components.map(toApiComponent) };
}

export function stepApi(lib: Library): StepResult {
	const changed = writeAtomic(PATHS.apiJson, stableJson(apiJson(lib)));
	const props = lib.components.reduce((s, c) => s + c.parts.reduce((t, p) => t + p.props.length, 0), 0);
	const examples = lib.components.reduce((s, c) => s + c.examples.length, 0);
	return {
		step: 'api',
		ok: true,
		summary: `${rel(PATHS.apiJson)} — ${lib.components.length} components, ${props} props, ${examples} examples${changed ? '' : ' · unchanged'}`
	};
}

export async function runGen(): Promise<{ results: StepResult[]; lib: Library; layers: LayerBuild }> {
	const results: StepResult[] = [];
	results.push(await stepSprings());
	const layers = buildLayers();
	results.push(stepStyles(layers));
	const lib = analyzeLibrary();
	results.push(stepBarrel(lib));
	results.push(stepApi(lib));
	return { results, lib, layers };
}
