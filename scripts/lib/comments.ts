// Moving a component folder's JSDoc out of the source and into comments.md.
//
// One entry is addressed by (file, declaration label, member path). The markdown
// is the only copy while the annotations are stripped; `comments-restore.ts`
// puts them back by path, so the round trip survives edits elsewhere.

import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { extractScripts } from './svelte.ts';
import { PATHS, ROOT, exists, isDir, lineAt, listDir, readText, rel } from './util.ts';

export const MARKER = '<!-- generated by scripts/comments-strip.ts — source JSDoc lives here, keyed by declaration and member. -->';
export const FILE_NAME = 'comments.md';

/** Annotations of this scope: `all` strips every JSDoc, `props` only `interface Props`. */
export type Scope = 'all' | 'props';

export interface Site {
	label: string;
	/** Member path inside the declaration; '' for the declaration itself. */
	path: string;
	node: ts.Node;
}

export interface DocEntry {
	file: string;
	label: string;
	path: string;
	body: string;
	line: number;
}

export interface Found extends DocEntry {
	/** Range to cut from the source: the comment run, plus the gap before the node. */
	start: number;
	end: number;
	indent: string;
}

// ── naming ───────────────────────────────────────────────────────────────────

function nameOf(node: ts.Node): string | null {
	const name = (node as { name?: ts.Node }).name;
	if (!name) return null;
	if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isPrivateIdentifier(name)) return name.text;
	return name.getText(name.getSourceFile());
}

function docsOf(node: ts.Node): ts.JSDoc[] {
	return (node as unknown as { jsDoc?: ts.NodeArray<ts.JSDoc> }).jsDoc?.slice() ?? [];
}

// ── the documentable sites of one module ─────────────────────────────────────

export function sites(sf: ts.SourceFile): Site[] {
	const out: Site[] = [];
	const add = (node: ts.Node, label: string, p: string) => out.push({ label, path: p, node });

	const members = (list: readonly ts.Node[], label: string, prefix: string) => {
		for (const m of list) {
			const name = nameOf(m);
			if (!name) continue;
			const p = prefix ? `${prefix}.${name}` : name;
			add(m, label, p);
			const type = (m as ts.PropertySignature | ts.PropertyDeclaration).type;
			if (!type) continue;
			if (ts.isTypeLiteralNode(type)) members(type.members, label, p);
			else if (ts.isUnionTypeNode(type))
				for (const alt of type.types) if (ts.isTypeLiteralNode(alt)) members(alt.members, label, p);
		}
	};

	const visit = (n: ts.Node): void => {
		if (ts.isInterfaceDeclaration(n)) {
			const label = `interface ${n.name.text}`;
			add(n, label, '');
			members(n.members, label, '');
			return;
		}
		if (ts.isTypeAliasDeclaration(n)) {
			const label = `type ${n.name.text}`;
			add(n, label, '');
			if (ts.isTypeLiteralNode(n.type)) members(n.type.members, label, '');
			return;
		}
		if (ts.isClassDeclaration(n) && n.name) {
			const label = `class ${n.name.text}`;
			add(n, label, '');
			members(n.members, label, '');
			return;
		}
		if (ts.isEnumDeclaration(n)) {
			const label = `enum ${n.name.text}`;
			add(n, label, '');
			for (const m of n.members) {
				const name = nameOf(m);
				if (name) add(m, label, name);
			}
			return;
		}
		if (ts.isFunctionDeclaration(n) && n.name) add(n, `function ${n.name.text}`, '');
		else if (ts.isVariableStatement(n)) {
			for (const d of n.declarationList.declarations) {
				if (!ts.isIdentifier(d.name)) continue;
				add(n, `const ${d.name.text}`, '');
				add(d, `const ${d.name.text}`, '');
			}
		}
		ts.forEachChild(n, visit);
	};
	ts.forEachChild(sf, visit);
	return out;
}

// ── reading the source ───────────────────────────────────────────────────────

function rawBody(code: string, doc: ts.JSDoc): string {
	const raw = code.slice(doc.getStart(), doc.getEnd()).replace(/^\/\*\*/, '').replace(/\*\/$/, '');
	return raw
		.split('\n')
		.map((l) => l.replace(/^\s*\*?\s?/, ''))
		.join(' ')
		.replace(/\s+/g, ' ')
		.trim();
}

function indentAt(source: string, pos: number): string {
	const start = source.lastIndexOf('\n', pos - 1) + 1;
	const lead = source.slice(start, pos);
	return /^[ \t]*$/.test(lead) ? lead : '';
}

/** Every JSDoc-bearing declaration of a `.svelte` or `.ts` source, with cut ranges. */
export function findDocs(source: string, fileName: string, scope: Scope = 'all'): Found[] {
	const blocks = fileName.endsWith('.svelte')
		? extractScripts(source).filter((b) => b.ts)
		: [{ content: source, offset: 0 }];
	const out: Found[] = [];
	for (const b of blocks) {
		const sf = ts.createSourceFile(`${fileName}.ts`, b.content, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
		for (const site of sites(sf)) {
			if (scope === 'props' && !(site.label === 'interface Props' || site.label === 'type Props')) continue;
			const docs = docsOf(site.node);
			if (!docs.length) continue;
			// Only the comment adjacent to the node is its own; anything stacked above it
			// is an orphan that belongs to nothing, and stays in the source.
			const doc = docs[docs.length - 1];
			const start = b.offset + doc.getStart(sf);
			const nodeStart = b.offset + site.node.getStart(sf);
			const body = rawBody(b.content, doc);
			if (!body) continue;
			out.push({
				file: fileName,
				label: site.label,
				path: site.path,
				body,
				line: lineAt(source, nodeStart),
				start,
				end: nodeStart,
				indent: indentAt(source, nodeStart)
			});
		}
	}
	return dedupe(out);
}

/** One entry per site, and no range nested inside another. */
function dedupe(found: Found[]): Found[] {
	const byKey = new Set<string>();
	const keep: Found[] = [];
	for (const e of found.sort((a, b) => a.start - b.start || b.end - a.end)) {
		const key = `${e.file}\u0000${e.label}\u0000${e.path}`;
		if (byKey.has(key)) continue;
		const prev = keep[keep.length - 1];
		if (prev && e.start < prev.end) continue;
		byKey.add(key);
		keep.push(e);
	}
	return keep;
}

export function stripDocs(source: string, found: Found[]): string {
	let out = source;
	for (const e of [...found].sort((a, b) => b.start - a.start)) out = out.slice(0, e.start) + out.slice(e.end);
	return out;
}

/**
 * A source with every JSDoc rewritten as a canonical one-liner and every run of
 * whitespace collapsed. Two sources that differ only in line breaks, indentation
 * or ` * ` leaders squash equal; a comment in the wrong place does not.
 */
export function squashSource(source: string): string {
	return source
		.replace(/\/\*\*[\s\S]*?\*\//g, (m) => {
			const body = m
				.slice(3, -2)
				.split('\n')
				.map((l) => l.replace(/^\s*\*?\s?/, ''))
				.join(' ')
				.replace(/\s+/g, ' ')
				.trim();
			return `/** ${body} */`;
		})
		.replace(/\s+/g, ' ')
		.trim();
}

// ── comments.md ──────────────────────────────────────────────────────────────

const BULLET = /^- `(.+?)` :: (.*)$/;

export function renderMarkdown(relDir: string, entries: DocEntry[]): string {
	const files = new Map<string, DocEntry[]>();
	for (const e of entries) {
		const list = files.get(e.file) ?? [];
		list.push(e);
		files.set(e.file, list);
	}
	const out: string[] = [`# comments — ${relDir}`, '', MARKER, ''];
	out.push('The JSDoc for this folder’s source lives here. `pnpm comments:restore` puts it back.');
	for (const [file, list] of files) {
		out.push('', `## ${file}`);
		for (const [label, group] of groupBy(list, (e) => e.label)) {
			out.push('', `### \`${label}\``);
			const own = group.find((e) => e.path === '');
			if (own) out.push('', own.body);
			const nested = group.filter((e) => e.path !== '');
			if (nested.length) out.push('');
			for (const e of nested) out.push(`- \`${e.path}\` :: ${e.body}`);
		}
	}
	out.push('');
	return out.join('\n');
}

export function parseMarkdown(source: string): DocEntry[] {
	const out: DocEntry[] = [];
	let file = '';
	let label = '';
	let ownNext = false;
	for (const raw of source.split('\n')) {
		const line = raw.trimEnd();
		if (line.startsWith('## ') && !line.startsWith('### ')) {
			file = line.slice(3).trim();
			label = '';
			ownNext = false;
			continue;
		}
		if (line.startsWith('### `')) {
			label = line.slice(5).replace(/`\s*$/, '').trim();
			ownNext = true;
			continue;
		}
		if (!file || !label) continue;
		const bullet = BULLET.exec(line);
		if (bullet) {
			out.push({ file, label, path: bullet[1], body: bullet[2].trim(), line: 0 });
			ownNext = false;
			continue;
		}
		if (ownNext && line.trim()) {
			out.push({ file, label, path: '', body: line.trim(), line: 0 });
			ownNext = false;
		}
	}
	return out;
}

function groupBy<T>(list: T[], key: (item: T) => string): [string, T[]][] {
	const map = new Map<string, T[]>();
	for (const item of list) {
		const k = key(item);
		const group = map.get(k) ?? [];
		group.push(item);
		map.set(k, group);
	}
	return [...map];
}

// ── writing the annotations back ─────────────────────────────────────────────

const WIDTH = 100;

function renderDoc(body: string, indent: string): string {
	const one = `/** ${body} */`;
	if (indent.length + one.length <= WIDTH + 20) return `${one}\n${indent}`;
	const lines: string[] = [];
	let current = '';
	for (const word of body.split(' ')) {
		if (current && indent.length + 3 + current.length + word.length > WIDTH) {
			lines.push(current.trimEnd());
			current = '';
		}
		current += `${word} `;
	}
	if (current.trim()) lines.push(current.trimEnd());
	return `/**\n${lines.map((l) => `${indent} * ${l}`).join('\n')}\n${indent} */\n${indent}`;
}

export interface Inserted {
	output: string;
	applied: number;
	missing: DocEntry[];
}

export function insertDocs(source: string, fileName: string, entries: DocEntry[]): Inserted {
	const blocks = fileName.endsWith('.svelte')
		? extractScripts(source).filter((b) => b.ts)
		: [{ content: source, offset: 0 }];
	const at = new Map<string, { pos: number; indent: string }>();
	for (const b of blocks) {
		const sf = ts.createSourceFile(`${fileName}.ts`, b.content, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
		for (const site of sites(sf)) {
			const key = `${site.label}\u0000${site.path}`;
			if (at.has(key)) continue;
			const pos = b.offset + site.node.getStart(sf);
			at.set(key, { pos, indent: indentAt(source, pos) });
		}
	}
	const inserts: { pos: number; text: string }[] = [];
	const missing: DocEntry[] = [];
	for (const e of entries) {
		const target = at.get(`${e.label}\u0000${e.path}`);
		if (!target) {
			missing.push(e);
			continue;
		}
		inserts.push({ pos: target.pos, text: renderDoc(e.body, target.indent) });
	}
	let output = source;
	for (const ins of inserts.sort((a, b) => b.pos - a.pos)) output = output.slice(0, ins.pos) + ins.text + output.slice(ins.pos);
	return { output, applied: inserts.length, missing };
}

// ── folders ──────────────────────────────────────────────────────────────────

export interface Folder {
	kit: string;
	slug: string;
	dir: string;
	relDir: string;
}

export function componentFolders(): Folder[] {
	const out: Folder[] = [];
	for (const kit of listDir(PATHS.components, 'dir')) {
		const kitDir = path.join(PATHS.components, kit);
		if (!isDir(kitDir)) continue;
		for (const slug of listDir(kitDir, 'dir')) {
			const dir = path.join(kitDir, slug);
			out.push({ kit, slug, dir, relDir: `src/lib/components/${kit}/${slug}` });
		}
	}
	return out;
}

/** The annotatable source of a folder: parts and their logic modules, never doc.ts/index.ts/examples. */
export function sourceFiles(dir: string): string[] {
	const out: string[] = [];
	for (const name of listDir(dir, 'file')) {
		if ((name.endsWith('.svelte') || name.endsWith('.ts')) && name !== 'doc.ts' && name !== 'index.ts') out.push(name);
	}
	for (const sub of listDir(dir, 'dir')) {
		if (sub === 'examples') continue;
		for (const nested of sourceFiles(path.join(dir, sub))) out.push(`${sub}/${nested}`);
	}
	return out;
}

export function commentsPath(dir: string): string {
	return path.join(dir, FILE_NAME);
}

export function readComments(dir: string): DocEntry[] | null {
	const text = readText(commentsPath(dir));
	return text === null ? null : parseMarkdown(text);
}

export function writeComments(dir: string, relDir: string, entries: DocEntry[]): void {
	fs.writeFileSync(commentsPath(dir), renderMarkdown(relDir, entries), 'utf8');
}

export function writeSource(file: string, text: string): void {
	fs.writeFileSync(file, text, 'utf8');
}

// ── the same annotations, for the docs pipeline ─────────────────────────────

/** A stripped entry's text split the way `jsdocOf` splits an inline comment. */
export function splitBody(body: string): { description: string; defaultTag: string | null } {
	const at = body.search(/\s@default\b/);
	if (at === -1) return { description: body.trim(), defaultTag: null };
	const rest = body
		.slice(at)
		.replace(/^\s*@default\s*/, '')
		.trim()
		.replace(/^`(.*)`$/, '$1');
	return { description: body.slice(0, at).trim(), defaultTag: rest || null };
}

/** `<file>\0<declaration label>\0<member path>` → body, for folders whose JSDoc is stripped. */
export type DocIndex = Map<string, string>;

export function docIndex(entries: DocEntry[]): DocIndex {
	const index: DocIndex = new Map();
	for (const e of entries) index.set(`${e.file}\u0000${e.label}\u0000${e.path}`, e.body);
	return index;
}

/** The folder's comments.md as an index, or null when the annotations are still inline. */
export function readDocIndex(dir: string): DocIndex | null {
	const entries = readComments(dir);
	return entries === null ? null : docIndex(entries);
}

