// ── the doc block: page prose that is not source JSDoc ──────────────────────

/**
 * A `comments.md` may carry one JSON block for the page itself — the summary,
 * the description, the feature bullets, the accessibility and keyboard notes —
 * exactly the keys `defineDoc` used to take:
 *
 * ```md
 * <!-- doc
 * { "summary": "One sentence.", "description": "…", "accessibility": ["…"] }
 * -->
 * ```
 *
 * The block belongs in the component folder's `comments.md`. A kit folder's
 * `comments.md` may hold blocks for several components, each keyed by slug:
 * `<!-- doc:data-table { … } -->`. Nothing else in the file is affected.
 */
export const DOC_MARKER = /<!--\s*doc(\s*:\s*([a-z0-9-]+))?\s*([\s\S]*?)-->/g;

export interface DocBlock {
	value: Record<string, unknown> | null;
	error: string | null;
	/** Where it was found, for the message. */
	file: string | null;
}

function parseDocBlock(text: string, own: boolean, file: string, want: string): DocBlock {
	for (const match of text.matchAll(DOC_MARKER)) {
		const slug = match[2] ?? null;
		// The folder's own file holds a bare `<!-- doc -->`. A group file holds
		// one block per component, keyed by slug, and nothing else counts.
		if (own ? slug !== null : slug !== want) continue;
		let value: unknown;
		try {
			value = JSON.parse(match[3].trim());
		} catch (err) {
			return { value: null, error: `doc block is not valid JSON: ${(err as Error).message}`, file };
		}
		if (value === null || typeof value !== 'object' || Array.isArray(value))
			return { value: null, error: 'doc block must be a JSON object', file };
		return { value: value as Record<string, unknown>, error: null, file };
	}
	return { value: null, error: null, file: null };
}

/**
 * The page prose for one component: its own folder's `comments.md` first, then
 * its kit's (`src/lib/components/<kit>/comments.md`, keyed by slug).
 */
export function readDocBlock(dir: string, kitDir: string, slug: string): DocBlock {
	const own = readText(path.join(dir, FILE_NAME));
	if (own !== null) {
		const found = parseDocBlock(own, true, path.join(dir, FILE_NAME), slug);
		if (found.value || found.error) return found;
	}
	const group = readText(path.join(kitDir, FILE_NAME));
	if (group !== null) {
		const found = parseDocBlock(group, false, path.join(kitDir, FILE_NAME), slug);
		if (found.value || found.error) return found;
	}
	return { value: null, error: null, file: null };
}
