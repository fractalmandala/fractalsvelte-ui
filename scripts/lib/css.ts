// The extension layer: concatenation into custom.css, class harvesting, and a
// small brace-aware CSS parser (enough for plain, token-only stylesheets).

import path from 'node:path';
import { PATHS, blank, byCodepoint, cssCodeLines, lineAt, listDir, readText } from './util.ts';

export interface LayerFile {
	/** Path relative to the layers folder: `10-surfaces.css`, `kits/actions.css`. */
	name: string;
	full: string;
	source: string;
}

export interface CssRule {
	prelude: string;
	declarations: string[];
	children: CssRule[];
	line: number;
}

export interface ClassEntry {
	class: string;
	file: string;
	selector: string;
	declarations: string;
}

export interface LayerSegment {
	file: string;
	/** First line of the segment's content in custom.css (1-based). */
	start: number;
	lines: number;
}

export interface LayerBuild {
	files: LayerFile[];
	css: string;
	segments: LayerSegment[];
	classes: ClassEntry[];
	/** Every class named in any selector of the layers (compound selectors included), plus what fractalstyler's linter harvests. */
	harvested: Set<string>;
	codeLines: number;
}

export function readLayers(): LayerFile[] {
	const out: LayerFile[] = [];
	for (const name of listDir(PATHS.layers, 'file').filter((n) => n.endsWith('.css'))) {
		const full = path.join(PATHS.layers, name);
		out.push({ name, full, source: readText(full) ?? '' });
	}
	for (const name of listDir(PATHS.kitLayers, 'file').filter((n) => n.endsWith('.css'))) {
		const full = path.join(PATHS.kitLayers, name);
		out.push({ name: `kits/${name}`, full, source: readText(full) ?? '' });
	}
	return out;
}

const BANNER =
	'/* GENERATED by scripts/gen.ts from src/lib/styles/layers/**.css — do not edit. Edit the layer files and run `pnpm gen`. */';

export function buildLayers(files: LayerFile[] = readLayers()): LayerBuild {
	const parts: string[] = [BANNER, ''];
	const segments: LayerSegment[] = [];
	let line = 3;
	for (const f of files) {
		const body = f.source.replace(/\s+$/, '');
		parts.push(`/* ── ${f.name} ── */`);
		line += 1;
		const n = body === '' ? 0 : body.split('\n').length;
		segments.push({ file: f.name, start: line, lines: n });
		if (n > 0) parts.push(body);
		parts.push('');
		line += n + 1;
	}
	const css = parts.join('\n');

	const seen = new Map<string, ClassEntry>();
	for (const f of files) {
		for (const entry of harvestRuleClasses(f.name, f.source)) {
			if (!seen.has(entry.class)) seen.set(entry.class, entry);
		}
	}
	const classes = [...seen.values()].sort((a, b) => byCodepoint(a.class, b.class));

	return {
		files,
		css,
		segments,
		classes,
		harvested: new Set([...harvestLikeLinter(css), ...classes.map((e) => e.class)]),
		codeLines: files.reduce((sum, f) => sum + cssCodeLines(f.source), 0)
	};
}

/** Exactly the regex fractalstyler's `lint` uses on a consumer's custom.css. */
export function harvestLikeLinter(css: string): Set<string> {
	const names = new Set<string>();
	for (const m of css.matchAll(/(?:^|[\s,{}])(\.)([a-zA-Z][a-zA-Z0-9_-]*)/g)) names.add(m[2]);
	return names;
}

/** Map a line of the generated custom.css back to its layer file. */
export function mapCustomLine(segments: LayerSegment[], line: number): { file: string; line: number } | null {
	for (const s of segments) {
		if (line >= s.start && line < s.start + s.lines) return { file: s.file, line: line - s.start + 1 };
	}
	return null;
}

// ── parser ───────────────────────────────────────────────────────────────────

function stripComments(src: string): string {
	return src.replace(/\/\*[\s\S]*?\*\//g, (m) => blank(m));
}

function skipString(src: string, i: number): number {
	const q = src[i];
	let j = i + 1;
	while (j < src.length && src[j] !== q) {
		if (src[j] === '\\') j++;
		j++;
	}
	return j;
}

function matchBrace(src: string, open: number): number {
	let depth = 0;
	for (let i = open; i < src.length; i++) {
		const c = src[i];
		if (c === '"' || c === "'") i = skipString(src, i);
		else if (c === '{') depth++;
		else if (c === '}') {
			depth--;
			if (depth === 0) return i;
		}
	}
	return src.length;
}

function parseBlock(src: string, from: number, to: number, full: string): { rules: CssRule[]; decls: string[] } {
	const rules: CssRule[] = [];
	const decls: string[] = [];
	let seg = from;
	let paren = 0;
	for (let i = from; i < to; i++) {
		const c = src[i];
		if (c === '"' || c === "'") {
			i = skipString(src, i);
		} else if (c === '(') paren++;
		else if (c === ')') paren = Math.max(0, paren - 1);
		else if (c === ';' && paren === 0) {
			const d = src.slice(seg, i).trim();
			if (d) {
				// `@import …;` and friends at block level are statements, not declarations.
				if (!d.startsWith('@')) decls.push(d.replace(/\s+/g, ' '));
			}
			seg = i + 1;
		} else if (c === '{' && paren === 0) {
			const close = matchBrace(src, i);
			const prelude = src.slice(seg, i).trim().replace(/\s+/g, ' ');
			const inner = parseBlock(src, i + 1, Math.min(close, to), full);
			rules.push({ prelude, declarations: inner.decls, children: inner.rules, line: lineAt(full, seg + (src.slice(seg, i).length - src.slice(seg, i).trimStart().length)) });
			i = close;
			seg = close + 1;
		}
	}
	const tail = src.slice(seg, to).trim();
	if (tail && !tail.startsWith('@')) decls.push(tail.replace(/\s+/g, ' '));
	return { rules, decls };
}

export function parseCss(source: string): CssRule[] {
	const src = stripComments(source);
	return parseBlock(src, 0, src.length, source).rules;
}

const SKIP_AT = /^@(keyframes|-webkit-keyframes|font-face|property|counter-style|page|font-feature-values)\b/;

function harvestRuleClasses(file: string, source: string): ClassEntry[] {
	const out: ClassEntry[] = [];
	const visit = (rules: CssRule[]) => {
		for (const r of rules) {
			if (r.prelude.startsWith('@')) {
				if (!SKIP_AT.test(r.prelude)) visit(r.children);
				continue;
			}
			const names = new Set<string>();
			for (const m of r.prelude.matchAll(/\.(-?[a-zA-Z_][\w-]*)/g)) names.add(m[1]);
			for (const name of names) {
				out.push({ class: name, file, selector: r.prelude, declarations: r.declarations.join('; ') });
			}
			visit(r.children);
		}
	};
	visit(parseCss(source));
	return out;
}
