/**
 * Generates `src/lib/styles/layers/01-springs.css` — the CSS spring tokens.
 *
 * For every preset in `springs`: `--spring-<name>: linear(…)` (the true spring
 * curve as a CSS easing) and `--spring-<name>-ms: <n>ms` (its settle time).
 *
 * Run directly (`node scripts/gen-springs.ts`) or call `run()` from `scripts/gen.ts`.
 */
import { renameSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { springs, springEasing, type SpringPreset } from '../src/lib/motion/spring.ts';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src/lib/styles/layers/01-springs.css');

/** Build the stylesheet text. Deterministic: same presets → byte-identical output. */
export function generateSprings(): string {
	const names = Object.keys(springs) as SpringPreset[];
	const lines: string[] = [
		'/* GENERATED by scripts/gen-springs.ts — do not edit */',
		'',
		':root {'
	];
	for (const name of names) {
		const { easing, duration } = springEasing(name, 40);
		lines.push(`\t--spring-${name}: ${easing};`);
		lines.push(`\t--spring-${name}-ms: ${duration}ms;`);
	}
	lines.push('}', '');
	return lines.join('\n');
}

/** Write the generated stylesheet atomically (temp file + rename). */
export async function run(): Promise<void> {
	const css = generateSprings();
	mkdirSync(dirname(OUT), { recursive: true });
	const tmp = `${OUT}.${process.pid}.tmp`;
	writeFileSync(tmp, css, 'utf8');
	renameSync(tmp, OUT);
}

const invoked = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invoked) {
	await run();
	console.log(`gen-springs: wrote ${OUT}`);
}
