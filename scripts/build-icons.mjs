#!/usr/bin/env node
// @ts-nocheck
/**
 * Generates the icon packs shipped with the package:
 *   icons/<set>/*.svg  ->  src/lib/icons/<set>.ts  (IconNode arrays, tree-shakeable)
 *
 * The raw SVGs stay at the repo root (icons/) and are not published: every icon's
 * markup is inlined into the generated module, so dist/ needs no .svg files.
 *
 * Run: node scripts/build-icons.mjs
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'icons');
const OUT = join(root, 'src/lib/icons');

/** Both packs render at 24x24 with a single paint group; prefixes keep them apart. */
const SETS = [
	{ dir: 'keylinestroke', file: 'keylinestroke', prefix: 'kl' },
	{ dir: 'keylinefill', file: 'keylinefill', prefix: 'klf' }
];

const PAINT = ['fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin'];

const pascal = (kebab) =>
	kebab
		.split('-')
		.map((w) => (w ? w[0].toUpperCase() + w.slice(1) : ''))
		.join('');

const attrMap = (s) =>
	Object.fromEntries([...s.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));

/** SVG -> IconNode: paint attrs hoisted onto one <g>, children kept in order. */
function toIconNode(svg, file) {
	const open = svg.match(/<svg\b([^>]*)>/);
	if (!open) throw new Error(`${file}: no <svg> root`);
	const rootAttrs = attrMap(open[1]);
	if (rootAttrs.viewBox !== '0 0 24 24') throw new Error(`${file}: unexpected viewBox ${rootAttrs.viewBox}`);

	const paint = Object.fromEntries(PAINT.filter((k) => k in rootAttrs).map((k) => [k, rootAttrs[k]]));
	const children = [...svg.matchAll(/<(\w+)\b([^>]*?)\/>/g)].map(([, tag, a]) => [tag, attrMap(a)]);
	if (children.length === 0) throw new Error(`${file}: no drawable children`);

	return [['g', paint], ...children];
}

const line = ([tag, attrs]) => `['${tag}', ${JSON.stringify(attrs)}]`;

async function buildSet({ dir, file, prefix }) {
	const dirPath = join(SRC, dir);
	const files = (await readdir(dirPath)).filter((f) => f.endsWith('.svg')).sort();

	const icons = await Promise.all(
		files.map(async (f) => {
			const svg = await readFile(join(dirPath, f), 'utf8');
			return [prefix + pascal(f.replace(/\.svg$/, '')), toIconNode(svg, `${dir}/${f}`)];
		})
	);

	icons.sort(([a], [b]) => a.localeCompare(b));
	const seen = new Set();
	for (const [name] of icons) {
		if (seen.has(name)) throw new Error(`${dir}: duplicate export ${name}`);
		seen.add(name);
	}

	const body = icons.map(([name, node]) => `export const ${name}: IconNode = [${node.map(line).join(', ')}];`);

	const ts = `// AUTO-GENERATED by scripts/build-icons.mjs from icons/${dir}/*.svg — do not edit by hand.
// Regenerate: node scripts/build-icons.mjs
import type { IconNode } from './types.js';

${body.join('\n')}
`;

	await writeFile(join(OUT, `${file}.ts`), ts, 'utf8');
	return { dir, file, count: icons.length, bytes: ts.length };
}

const results = await Promise.all(SETS.map(buildSet));
for (const { file, count, bytes } of results)
	console.log(`src/lib/icons/${file}.ts — ${count} icons, ${(bytes / 1024).toFixed(0)} KB`);
